// Writes test/browser/fixtures.js: the synthetic fixtures (tools/make-synthetic-fixtures.mjs) as base64 so the browser test page
// can replay their exact bytes without any network request. test/browser-fixtures.test.js
// fails if the file drifts from test/fixtures/. Run: node tools/make-browser-fixtures.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildFixturesModule() {
  const dir = path.join(ROOT, 'test/fixtures');
  const names = fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort();
  const entries = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(fs.readFileSync(path.join(dir, n)).toString('base64'))},`);
  return `// GENERATED by tools/make-browser-fixtures.mjs from test/fixtures/ (synthetic twin data, safe to publish).\n`
    + `export const FIXTURES_B64 = {\n${entries.join('\n')}\n};\n\n`
    + `export function fixtureBytes(name) {\n  const s = atob(FIXTURES_B64[name]);\n  const b = new Uint8Array(s.length);\n  for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i);\n  return b;\n}\n\n`
    + `export const fixtureText = (name) => String.fromCharCode(...fixtureBytes(name));\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(ROOT, 'test/browser/fixtures.js');
  fs.writeFileSync(out, buildFixturesModule());
  console.log(`wrote ${path.relative(ROOT, out)} (${fs.statSync(out).size} bytes)`);
}
